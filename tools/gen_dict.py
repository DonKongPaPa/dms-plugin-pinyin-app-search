#!/usr/bin/env python3
"""生成 data/pinyin-dict.js —— 供 PinyinApps.qml 直接 import 的拼音映射表。

输出两个对象：
  syllables  : { "jie": "解姐街...", ... }   音节 -> 该读音的汉字（约 100KB）
  polyphones : { "乐": ["le","yue"], ... }   多音字，按常见度排序（约 400 项）

只保留 BMP 内的 CJK（U+3400–U+9FFF），覆盖所有实际应用名。
重新生成: python3 tools/gen_dict.py   （需要 pypinyin）
"""
import json
import os
import collections
from pypinyin import pinyin, Style

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "pinyin-dict.js")


def main():
    buckets = collections.defaultdict(list)
    poly = {}
    total = 0

    for cp in range(0x3400, 0xA000):
        ch = chr(cp)
        try:
            readings = pinyin(ch, style=Style.NORMAL, heteronym=True, errors="ignore")
        except Exception:
            continue
        if not readings or not readings[0]:
            continue
        rs = []
        for r in readings[0]:
            r = r.strip()
            if r and r.isascii() and r.isalpha() and r not in rs:
                rs.append(r)
        if not rs:
            continue
        total += 1
        for r in rs[:4]:
            buckets[r].append(ch)
        if len(rs) > 1:
            poly[ch] = rs[:4]

    syl = {k: "".join(v) for k, v in sorted(buckets.items())}
    body = (
        "// AUTO-GENERATED by tools/gen_dict.py — do not edit by hand.\n"
        "// source: pypinyin %s\n"
        ".pragma library\n\n"
        "var syllables = %s;\n\n"
        "var polyphones = %s;\n"
    ) % (_version(), json.dumps(syl, ensure_ascii=False, separators=(",", ":")),
         json.dumps(poly, ensure_ascii=False, separators=(",", ":")))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(body)

    print(f"chars={total} syllables={len(syl)} polyphones={len(poly)} "
          f"bytes={len(body.encode('utf-8'))} -> {os.path.normpath(OUT)}")


def _version():
    try:
        import pypinyin
        return getattr(pypinyin, "__version__", "?")
    except Exception:
        return "?"


if __name__ == "__main__":
    main()
